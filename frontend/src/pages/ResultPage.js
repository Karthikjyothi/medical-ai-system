import { useEffect, useState } from "react";
import Sidebar from "../components/Sidebar";
import ChatCopilot from "../components/ChatCopilot";
import API from "../services/api";

function ResultPage() {
  const result = JSON.parse(localStorage.getItem("diagnosis_result"));
  const user = JSON.parse(localStorage.getItem("user"));
  const [similarCases, setSimilarCases] = useState([]);

  const fetchSimilarCases = async () => {
    try {
      const res = await API.get(
        `/similar-cases/${user.id}/${result.diagnosis.predicted_disease}/${result.diagnosis.dataset}`
      );
      setSimilarCases(res.data.cases);
    } catch (err) {
      console.log(err);
    }
  };

  useEffect(() => {
    if (result) {
      fetchSimilarCases();
    }
  }, []);

  if (!result) return <h2>No diagnosis result found</h2>;

  const diagnosis = result.diagnosis;
  const radiologistOpinion = result.radiologist_opinion;
  const specialistOpinion = result.specialist_opinion;
  const preventiveAdvice = result.preventive_advice;

  const gradcamURL =
    "http://127.0.0.1:8000/" + result.gradcam_path.replace(/\\/g, "/");

  const reportURL =
    "http://127.0.0.1:8000/" + result.report_path.replace(/\\/g, "/");

  const getVerdict = () => {
    if (diagnosis.confidence >= 95 && diagnosis.uncertainty_level === "Low")
      return "High Reliability Clinical Prediction";
    if (diagnosis.uncertainty_level === "Medium")
      return "Moderate Reliability – Further Review Suggested";
    return "Specialist Clinical Validation Recommended";
  };

  return (
    <div style={{ display: "flex", background: "#edf2f7" }}>
      <Sidebar />

      <div
        style={{
          marginLeft: "260px",
          padding: "25px",
          width: "100%",
          minHeight: "100vh"
        }}
      >
        {/* HEADER */}
        <div style={heroBanner}>
          <h1 style={{ margin: 0 }}>Medical AI Diagnosis Intelligence Report</h1>
          <p style={{ marginTop: "10px", opacity: 0.9 }}>
            Autonomous clinical analysis generated by Universal Medical AI Platform
          </p>
        </div>

        {/* METRICS */}
        <div style={gridTop}>
          <div style={metricCard}>
            <h3>Detected Condition</h3>
            <h1 style={{ color: "#dc2626", marginBottom: "10px" }}>
              {diagnosis.predicted_disease}
            </h1>
            <p>Dataset: {diagnosis.dataset}</p>
            <div style={verdictBadge}>{getVerdict()}</div>
          </div>

          <div style={metricCard}>
            <h3>Confidence Analysis</h3>
            <h1>{diagnosis.confidence}%</h1>

            <div style={progressOuter}>
              <div
                style={{
                  ...progressInner,
                  width: `${diagnosis.confidence}%`
                }}
              ></div>
            </div>
          </div>

          <div style={metricCard}>
            <h3>Uncertainty Status</h3>
            <h1
              style={{
                color:
                  diagnosis.uncertainty_level === "Low"
                    ? "#16a34a"
                    : diagnosis.uncertainty_level === "Medium"
                    ? "#ca8a04"
                    : "#dc2626"
              }}
            >
              {diagnosis.uncertainty_level}
            </h1>
            <p>Uncertainty Score: {diagnosis.uncertainty}</p>
          </div>
        </div>

        {/* CONTENT */}
        <div style={mainGrid}>
          <div style={leftPanel}>
            <h2>Explainable AI Heatmap</h2>

            <div style={imageFrame}>
              <img
                src={gradcamURL}
                alt="GradCAM"
                style={{
                  width: "100%",
                  maxHeight: "420px",
                  objectFit: "contain",
                  borderRadius: "12px"
                }}
              />
            </div>

            <a href={reportURL} target="_blank" rel="noreferrer">
              <button style={downloadBtn}>Download PDF Clinical Report</button>
            </a>
          </div>

          <div style={rightPanel}>
            <h2>AI Medical Summary</h2>

            <div style={summaryBox}>
              <p style={{
                whiteSpace: "pre-line",
                lineHeight: "1.9",
                textAlign: "justify",
                fontSize: "14px",
                color: "#334155"
              }}>
                {result.ai_summary}
              </p>
            </div>
            <div style={{
  marginTop: "30px"
}}>
  <h2 style={{ marginBottom: "15px" }}>Virtual Specialist Intelligence Board</h2>

  <div style={{
    display: "grid",
    gridTemplateColumns: "1fr",
    gap: "20px"
  }}>
    <div style={specialistCard}>
      <h3 style={{ marginBottom: "10px", color: "#1d4ed8" }}>🧠 Radiologist Observation</h3>
      <p style={specialistText}>{radiologistOpinion}</p>
    </div>

    <div style={specialistCard}>
      <h3 style={{ marginBottom: "10px", color: "#dc2626" }}>👨‍⚕ Clinical Specialist Opinion</h3>
      <p style={specialistText}>{specialistOpinion}</p>
    </div>

    <div style={specialistCard}>
      <h3 style={{ marginBottom: "10px", color: "#16a34a" }}>💊 Preventive Care Recommendation</h3>
      <p style={specialistText}>{preventiveAdvice}</p>
    </div>
  </div>
</div>
          </div>
        </div>

        <div style={{ marginTop: "35px" }}>
          <h2 style={{ marginBottom: "15px" }}>Similar Historical Clinical Cases Retrieved</h2>

          <div style={{
            display: "grid",
            gridTemplateColumns: "repeat(3, 1fr)",
            gap: "20px"
          }}>
            {similarCases.map((item) => {
              const simGradcam =
                "http://127.0.0.1:8000/" + item.gradcam_image.replace(/\\/g, "/");

              return (
                <div key={item.id} style={similarCard}>
                  <img
                    src={simGradcam}
                    alt="similar"
                    style={{
                      width: "100%",
                      height: "130px",
                      objectFit: "cover",
                      borderRadius: "10px"
                    }}
                  />
                  <h3 style={{ color: "#dc2626", marginTop: "12px" }}>{item.predicted_disease}</h3>
                  <p>Confidence: {item.confidence}%</p>
                  <p>Dataset: {item.dataset}</p>
                  <p style={{ fontSize: "12px", color: "gray" }}>{item.created_at}</p>
                </div>
              );
            })}
          </div>
        </div>

        {/* CHATBOT */}
        <div style={{ marginTop: "30px" }}>
          <ChatCopilot diagnosis={diagnosis} />
        </div>
      </div>
    </div>
  );
}

